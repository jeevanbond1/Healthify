/// Starter Indian recipes, resolved by ingredient name so they log
/// with the same per-serving math as user recipes.
public func seedRecipes(foods: [FoodItem] = seedFoods) -> [Recipe] {
    let byName = Dictionary(uniqueKeysWithValues: foods.map { ($0.name, $0.id) })
    func ing(_ name: String, _ grams: Double) -> RecipeIngredient? {
        byName[name].map { RecipeIngredient(foodId: $0, grams: grams) }
    }
    func recipe(_ name: String, _ servings: Double,
                _ items: [(String, Double)]) -> Recipe? {
        let resolved = items.compactMap { ing($0.0, $0.1) }
        guard resolved.count == items.count else { return nil }
        return Recipe(name: name, servings: servings, ingredients: resolved)
    }
    return [
        recipe("Dal rice bowl", 1, [("Toor dal tadka (cooked)", 150), ("Cooked white rice", 150)]),
        recipe("Rajma rice bowl", 1, [("Rajma curry", 150), ("Cooked white rice", 150)]),
        recipe("Sambar rice bowl", 1, [("Sambar (cooked)", 150), ("Cooked white rice", 150)]),
        recipe("Palak paneer + 2 rotis", 1, [("Palak paneer", 150), ("Whole wheat roti", 80)]),
        recipe("Oats banana bowl", 1, [("Oats, dry", 40), ("Banana", 120), ("Milk, toned", 200)]),
        recipe("Egg plate (2 eggs + roti)", 1, [("Egg, boiled", 100), ("Whole wheat roti", 40)]),
        recipe("Paneer tikka + curd", 1, [("Paneer tikka", 120), ("Curd, plain", 100)]),
        recipe("Poha + peanuts plate", 1, [("Poha (cooked)", 150), ("Peanuts, roasted", 30)]),
    ].compactMap { $0 }
}
