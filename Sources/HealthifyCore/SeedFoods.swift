import Foundation

// Compact helper: positional macros, named micros. Keeps seed readable.
private func np(_ kcal: Double, _ p: Double, _ c: Double, _ f: Double,
                fiber: Double = 0, sugar: Double = 0, sat: Double = 0,
                na: Double = 0, k: Double = 0, ca: Double = 0,
                fe: Double = 0, mg: Double = 0, zn: Double = 0,
                va: Double = 0, vc: Double = 0, vd: Double = 0,
                b12: Double = 0, fol: Double = 0) -> NutrientProfile {
    var n = NutrientProfile()
    n.kcal = kcal; n.proteinG = p; n.carbsG = c; n.fatG = f
    n.fiberG = fiber; n.sugarG = sugar; n.satFatG = sat
    n.sodiumMg = na; n.potassiumMg = k; n.calciumMg = ca
    n.ironMg = fe; n.magnesiumMg = mg; n.zincMg = zn
    n.vitAMcg = va; n.vitCMg = vc; n.vitDMcg = vd
    n.vitB12Mcg = b12; n.folateMcg = fol
    return n
}

/// Explicit per-food measures: cup, katori, piece, glass…
private func U(_ label: String, _ grams: Double) -> ServingUnit {
    ServingUnit(label: label, grams: grams)
}

